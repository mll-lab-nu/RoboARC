#!/usr/bin/env python3
"""Harbor's dataset manifest for `harbor publish`, generated from the tasks; never committed.

Every task carries its own content digest in `tasks/<task>/DIGEST` (written last by scripts/task_conventions.py
`normalize`; ci_checks/check-dataset-manifest.sh recomputes it, and fails when tasks/dataset.toml is tracked). Nothing
in the repository lists the tasks: the list is the tasks/ directory, as in Terminal-Bench.

    python3 scripts/harbor/dataset_manifest.py write [--out FILE]   # default tasks/dataset.toml (ignored by git)

The dataset and task names use the `roboarc/` namespace of the tasks' own `[task].name` (task.toml; 1.0.0 used
`robot-coding-bench/`): the dataset is `roboarc/roboarc`.
Standard library only.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NAMESPACE = "roboarc"   # the namespace of every task's `[task].name` (scripts/task_conventions.py NAMESPACE)
HEADER = f'''# Dataset manifest for {NAMESPACE}/roboarc (generated by scripts/harbor/dataset_manifest.py; not committed)
# Publish using: harbor publish

[dataset]
name = "{NAMESPACE}/roboarc"
version = "{(ROOT / "images" / "roboarc" / "VERSION").read_text().strip()}"
description = "RoboARC: topological robot-manipulation puzzles in MuJoCo for coding agents; one replayable trajectory per frozen scene instance, in privileged and standard mode."
authors = []
keywords = [ "robotics", "manipulation", "mujoco", "code-as-policy", "harbor",]
'''
DIGEST = re.compile(r"sha256:[0-9a-f]{64}")


def render() -> str:
    out = [HEADER]
    bad = []
    for t in sorted(p for p in (ROOT / "tasks").iterdir() if (p / "task.toml").is_file()):
        f = t / "DIGEST"
        d = f.read_text().strip() if f.is_file() else ""
        if not DIGEST.fullmatch(d):
            bad.append(t.name)
            continue
        out.append(f'[[tasks]]\nname = "{NAMESPACE}/{t.name}"\ndigest = "{d}"\n')
    if bad:
        raise SystemExit(f"no valid DIGEST in {len(bad)} task(s), e.g. {bad[0]} (python3 scripts/task_conventions.py tasks/<task>)")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    if argv[:1] != ["write"]:
        raise SystemExit(__doc__)
    out = Path(argv[argv.index("--out") + 1]) if "--out" in argv else ROOT / "tasks" / "dataset.toml"
    text = render()
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} ({text.count('[[tasks]]')} tasks)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
